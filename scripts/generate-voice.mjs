import { execFileSync, spawn } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";
import process from "node:process";
import { clearInterval, setInterval } from "node:timers";
import prettier from "prettier";
import { collectVoiceLines } from "./lib/voice-lines.mjs";

const VOICE_DIR = resolve("public/assets/voice");
const MANIFEST_PATH = resolve("src/data/voiceManifest.ts");
const WORKER_PY = resolve("scripts/lib/voice-worker.py");
const MODEL_URL =
  "https://huggingface.co/nguyenvulebinh/VietVoice-TTS/resolve/main/model-bin.pt";
const REPO_URL = "https://github.com/nguyenvulebinh/VietVoice-TTS.git";

function argValue(prefix, fallback) {
  const hit = process.argv.find((a) => a.startsWith(prefix));
  return hit ? hit.slice(prefix.length) : fallback;
}

const manifestOnly = process.argv.includes("--manifest-only");
const prune = process.argv.includes("--prune");
const clean = process.argv.includes("--clean");
const workers = Math.max(1, Number(argValue("--workers=", "4")));
const limit = Number(argValue("--limit=", "0"));
const scratchBase = resolve(
  argValue("--work-dir=", "/tmp/little-wonders-voice"),
);
const venvDir = resolve(argValue("--venv=", join(scratchBase, "venv")));
const repoDir = resolve(argValue("--repo=", join(scratchBase, "repo")));
const cacheDir = resolve(argValue("--cache-dir=", join(scratchBase, "cache")));

async function writeManifest(lines) {
  const entries = {};
  for (const item of lines) {
    if (existsSync(join(VOICE_DIR, item.filename))) {
      entries[item.key] = item.url;
    }
  }
  const sorted = Object.fromEntries(
    Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)),
  );
  const raw =
    "// Auto-generated by scripts/generate-voice.mjs. Do not edit by hand.\n" +
    `export const voiceFiles: Record<string, string> = ${JSON.stringify(sorted, null, 2)};\n`;
  const formatted = await prettier.format(raw, { parser: "typescript" });
  writeFileSync(MANIFEST_PATH, formatted, "utf8");
  return Object.keys(sorted).length;
}

function patchPython39Compat(repo) {
  const ttsEngine = join(repo, "vietvoicetts/core/tts_engine.py");
  if (existsSync(ttsEngine)) {
    let text = readFileSync(ttsEngine, "utf8");
    if (text.includes("\nimport torch\n")) {
      text = text.replace("\nimport torch\n", "\n");
    }
    if (text.includes("reference_text + chunk")) {
      text = text.replace(
        "reference_text + chunk",
        'reference_text + " " + chunk',
      );
    }
    writeFileSync(ttsEngine, text, "utf8");
  }
  const audioProc = join(repo, "vietvoicetts/core/audio_processor.py");
  if (existsSync(audioProc)) {
    const text = readFileSync(audioProc, "utf8");
    if (text.includes("str | bytes")) {
      writeFileSync(
        audioProc,
        text
          .replace("from typing import List", "from typing import List, Union")
          .replace("str | bytes", "Union[str, bytes]"),
        "utf8",
      );
    }
  }
}

function ensureRuntime() {
  mkdirSync(scratchBase, { recursive: true });
  mkdirSync(cacheDir, { recursive: true });
  const py = join(venvDir, "bin/python3");
  if (!existsSync(py)) {
    execFileSync("python3", ["-m", "venv", venvDir], { stdio: "inherit" });
    execFileSync(
      join(venvDir, "bin/pip"),
      ["install", "numpy", "soundfile", "pydub", "tqdm", "onnxruntime"],
      { stdio: "inherit" },
    );
  }
  if (!existsSync(join(repoDir, "vietvoicetts/__init__.py"))) {
    execFileSync("git", ["clone", "--depth", "1", REPO_URL, repoDir], {
      stdio: "inherit",
    });
  }
  patchPython39Compat(repoDir);
  const modelFile = join(cacheDir, "model-bin.pt");
  if (!existsSync(modelFile)) {
    execFileSync("curl", ["-L", "-f", "-o", modelFile, MODEL_URL], {
      stdio: "inherit",
    });
  }
  return py;
}

async function runWorkers(py, missing) {
  const wavDir = join(scratchBase, "wavs");
  mkdirSync(wavDir, { recursive: true });
  const count = Math.min(workers, missing.length);
  const buckets = Array.from({ length: count }, () => []);
  missing.forEach((item, i) => {
    buckets[i % count].push({
      ttsText: item.ttsText,
      wav: join(wavDir, `${item.hash}.wav`),
      m4a: join(VOICE_DIR, item.filename),
    });
  });

  const threads = count >= 4 ? 3 : 4;
  await Promise.all(
    buckets.map(
      (bucket, idx) =>
        new Promise((resolvePromise, rejectPromise) => {
          const jobFile = join(scratchBase, `jobs-${idx}.json`);
          writeFileSync(jobFile, JSON.stringify(bucket), "utf8");
          const child = spawn(
            py,
            [WORKER_PY, jobFile, cacheDir, String(threads)],
            {
              stdio: "inherit",
              env: {
                ...process.env,
                OMP_NUM_THREADS: String(threads),
                PYTHONPATH: repoDir,
              },
            },
          );
          child.on("exit", (code) => {
            if (code === 0) resolvePromise();
            else rejectPromise(new Error(`Worker ${idx} exited with ${code}`));
          });
        }),
    ),
  );
}

async function main() {
  mkdirSync(VOICE_DIR, { recursive: true });
  const lines = await collectVoiceLines();

  if (prune) {
    const keep = new Set(lines.map((l) => l.filename));
    for (const file of readdirSync(VOICE_DIR)) {
      if (!keep.has(file)) unlinkSync(join(VOICE_DIR, file));
    }
  }

  let missing = lines.filter(
    (item) => !existsSync(join(VOICE_DIR, item.filename)),
  );
  if (limit > 0) missing = missing.slice(0, limit);

  if (manifestOnly || missing.length === 0) {
    const total = await writeManifest(lines);
    console.log(
      `Voice manifest up to date: ${total}/${lines.length} clips present.`,
    );
    if (clean && existsSync(scratchBase)) {
      rmSync(scratchBase, { recursive: true, force: true });
    }
    return;
  }

  console.log(
    `Generating ${missing.length} missing clip(s) across ${Math.min(workers, missing.length)} worker(s)...`,
  );
  const py = ensureRuntime();
  const ticker = setInterval(() => void writeManifest(lines), 15_000);
  try {
    await runWorkers(py, missing);
  } finally {
    clearInterval(ticker);
  }
  const total = await writeManifest(lines);
  console.log(`Generated voice manifest: ${total}/${lines.length} clips.`);
  if (clean && existsSync(scratchBase)) {
    rmSync(scratchBase, { recursive: true, force: true });
  }
}

await main();
