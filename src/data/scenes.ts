// Region scenes are data: adding a region means adding a scene entry here and its art, not rewriting the renderer.
export type SceneHotspot = {
  id: string;
  art: string;
  x: number;
  y: number;
  w: number;
  label: string;
  kind:
    | "tree"
    | "house"
    | "pal"
    | "reveal"
    | "revealed"
    | "flower"
    | "windmill"
    | "xylophone"
    | "interact"
    // Puts one item (gives) into the basket: coconut, shell, pinecone.
    | "gather"
    // Grows through stages one tap at a time (sandcastle, snowman, constellation); the last stage records the discovery.
    | "build";
  palId?: string;
  revealTarget?: string;
  revealedWhen?: string;
  requires?: string;
  line?: string;
  discovery?: string;
  nightOnly?: boolean;
  dayOnly?: boolean;
  shadow?: boolean;
  gives?: string;
  stages?: string[];
  stageLines?: string[];
};
export type RegionScene = {
  id: string;
  title: string;
  variant: "garden" | "pond" | "forest" | "beach" | "snow" | "stars";
  story: string;
  // Cloud and sun in the sky; the starry mountain has none by default.
  sky?: boolean;
  hasCloud?: boolean;
  cloud?: { x: number; y: number };
  hasHouse: boolean;
  hasCritters: boolean;
  signs: { text: string; className: string }[];
  hotspots: SceneHotspot[];
};
